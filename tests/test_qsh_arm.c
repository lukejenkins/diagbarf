/* Host unit test for the QSH-trace 0x9001 maskset SET arming payload.
 * Build+run: make -C apps/diagbarf test-qsh
 *
 * diagbarf can arm the 0x9D DIAG_QSH_TRACE_PAYLOAD_F stream on-device by
 * sending the golden QSH-trace maskset (subsys 0x44 / cmd 0x9001) that the
 * cfw3212's /data/diag.cfg frame 73 sends. This test pins the on-wire bytes to
 * the hardware-proven frame so the C encoder cannot drift from
 * the reference Python maskset builder — the same 180 bytes verified to arm
 * 0x9D on SDX55/SDX62. A mis-ordered or mis-sized maskset returns
 * status 1 on hardware (an ordering fault), so a byte diff here is the
 * cheap place to catch it, not the live unit. */
#include <assert.h>
#include <stdint.h>
#include <string.h>
#include <stdio.h>

#define DIAGBARF_FRAMING_TEST 1
#include "../diagbarf.c"

/* Frame 73 of the golden /data/diag.cfg (USC_1.1.99.0, md5 381bd429), i.e.
 * DIAG_SUBSYS_CMD_F(0x4B) + qsh_trace_arm_payload(). Dumped from the validated
 * Python builder:
 *   build_qsh_trace_maskset_set(GOLDEN_QSH_TRACE_PAIRS).hex()  == below. */
static const uint8_t GOLDEN_FRAME[] = {
    0x4b,0x44,0x01,0x90,0x2b,0x00,0x00,0x00,0x01,0x00,0x00,0x00,0x01,0x00,0x00,0x00,
    0x28,0x00,0x00,0x00,0x06,0x00,0x0f,0x00,0x09,0x00,0x3e,0x00,0x0b,0x00,0x03,0x00,
    0x0d,0x00,0x03,0x00,0x12,0x00,0x01,0x00,0x2a,0x00,0x03,0x00,0x2d,0x00,0x03,0x00,
    0x2f,0x00,0x07,0x00,0x34,0x00,0x0f,0x00,0x35,0x00,0x1f,0x00,0x36,0x00,0x03,0x00,
    0x3d,0x00,0x03,0x00,0x40,0x00,0x03,0x00,0x49,0x00,0x0b,0x00,0x4c,0x00,0x7f,0x08,
    0x4e,0x00,0x02,0x00,0x50,0x00,0x03,0x00,0x53,0x00,0x3f,0x00,0x54,0x00,0x0f,0x00,
    0x55,0x00,0x0f,0x00,0x56,0x00,0x03,0x00,0x57,0x00,0x03,0x00,0x58,0x00,0x01,0x00,
    0x59,0x00,0x0f,0x00,0x5e,0x00,0x01,0x00,0x60,0x00,0x07,0x00,0x61,0x00,0x03,0x00,
    0x62,0x00,0x0f,0x00,0x63,0x00,0x03,0x00,0x64,0x00,0x3f,0x00,0x65,0x00,0x03,0x00,
    0x68,0x00,0x03,0x00,0x69,0x00,0x0f,0x00,0x6b,0x00,0x03,0x00,0x6c,0x00,0x03,0x00,
    0x6d,0x00,0x03,0x00,0x6e,0x00,0x03,0x00,0x6f,0x00,0x01,0x00,0x70,0x00,0x01,0x00,
    0x71,0x00,0x03,0x00,
};

static void test_payload_matches_golden_frame_73(void) {
    uint8_t buf[512];
    size_t n = qsh_trace_arm_payload(buf, sizeof buf);
    /* payload is everything AFTER the 0x4B opcode send_recv() prepends. */
    assert(n == sizeof GOLDEN_FRAME - 1);
    assert(buf[0] == 0x44);                       /* subsys id */
    assert(buf[1] == 0x01 && buf[2] == 0x90);     /* cmd 0x9001, LE */
    assert(memcmp(buf, GOLDEN_FRAME + 1, n) == 0);
    printf("ok qsh_arm payload matches golden frame 73 (%zu bytes + 0x4B)\n", n);
}

static void test_maskset_is_strictly_ascending(void) {
    /* Ordering is load-bearing: hardware returns status 1 on any inversion. */
    size_t np = QSH_TRACE_NPAIRS;
    assert(np == 40);
    for (size_t i = 1; i < np; i++)
        assert(qsh_trace_golden_pairs[i][0] > qsh_trace_golden_pairs[i - 1][0]);
    printf("ok qsh_arm maskset strictly ascending (%zu pairs)\n", np);
}

static void test_short_buffer_is_rejected(void) {
    uint8_t tiny[8];
    assert(qsh_trace_arm_payload(tiny, sizeof tiny) == 0);
    printf("ok qsh_arm rejects short buffer\n");
}

int main(void) {
    test_payload_matches_golden_frame_73();
    test_maskset_is_strictly_ascending();
    test_short_buffer_is_rejected();
    printf("all qsh_arm tests passed\n");
    return 0;
}
